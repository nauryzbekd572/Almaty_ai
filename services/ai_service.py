import openai
from config.settings import settings

class AIService:
    def __init__(self):
        # Напрямую прокидываем ключ из настроек
        self.client = openai.AsyncOpenAI(api_key=settings.OPENAI_API_KEY)

    async def analyze_incident(self, user_text: str) -> dict:
        """
        Анализирует текст обращения, сопоставляет с концептами регламента 
        и возвращает категорию и правовое обоснование.
        """
        system_prompt = (
            "Ты — официальный ИИ-юрист проекта «Адал қоғам» (Справедливый Казахстан). "
            "Твоя задача — классифицировать обращение гражданина и выдать правовое заключение. "
            "Используй концепты: «Адал азамат» (честность, борьба с коррупцией, правовая грамотность), "
            "«Таза Қазақстан» (экология, благоустройство, чистота), «Закон и Порядок».\n\n"
            "Обязательно ссылайся на Конституцию Республики Казахстан 2026 года в понятной форме.\n"
            "Формат ответа должен быть строго в JSON с двумя ключами:\n"
            "1. 'category' — строка (например, 'Таза Қазақстан' или 'Адал азамат / Антикоррупция')\n"
            "2. 'resolution' — подробный юридический совет и план действий со ссылкой на нормы Конституции 2026."
        )

        try:
            response = await self.client.chat.completions.create(
                model="gpt-4o-mini",  # Для хакатона идеальный выбор по скорости/цене
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_text}
                ],
                response_format={"type": "json_object"}
            )
            
            # Парсим JSON-строку ответа
            import json
            result = json.loads(response.choices[0].message.content)
            return result
        except Exception as e:
            # Фалбэк-вариант (заглушка), если API упадет или кончатся токены во время защиты
            return {
                "category": "Закон и Порядок",
                "resolution": (
                    "На основании общих принципов Новой Конституции 2026 года и концепции «Закон и Порядок», "
                    "Ваше обращение принято к рассмотрению. Рекомендуется направить официальный запрос в местный исполнительный орган."
                )
            }
